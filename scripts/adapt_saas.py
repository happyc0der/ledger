"""Turn the HF `DeepMostInnovations/saas-sales-conversations` rows into a Ledger dataset.

Why this dataset: multi-turn buyer/rep conversations with speaker labels, personas, channel
and a REAL outcome label (converted or not). Notes are synthetic (GPT-4 generated by the
dataset authors), but they are messy, long, in many registers (sms, chat, email) and were
not written by us — the opposite of our planted benchmark. There are no planted anomaly
labels, so what we can score is win-probability calibration and prioritisation against the
outcome; everything else is reviewed by hand in the UI.

Mapping (documented, deterministic):
  deal         = one conversation; account = persona company; product = product_name
  activities   = one per turn; author = persona name (buyer) or the rep; type from channel;
                 dates spread over the conversation's span ending `gap` days before as_of,
                 where gap grows when the last customer turn is lukewarm (engagement < 0.5)
  stage        = rep-set, deliberately optimistic: from customer_engagement
  amount       = product_type band × company size (list prices in products.csv)
  contacts     = champion = persona (title = role); economic buyer unknown (realistic)
  ground truth = outcome (1 → Won, 0 → Lost); objection/action labels absent (n/a)
  history.csv  = the remaining conversations as closed deals → learned profile
"""
from __future__ import annotations

import glob
import json
import random
import sys
from datetime import timedelta
from pathlib import Path

import pandas as pd

SRC = Path(sys.argv[1]); OUT = Path(sys.argv[2]); N_OPEN = int(sys.argv[3]) if len(sys.argv) > 3 else 150
AS_OF = pd.Timestamp("2026-10-19")
rng = random.Random(3)
PRICE = {"Professional Services": 4800, "SaaS": 3600, "Enterprise Software": 12000, "Marketing": 2400, "Analytics": 5400,
         "Security": 8200, "HR": 3100, "Finance": 6500, "Developer Tools": 2900, "E-commerce": 3300}
SIZE_MULT = {"small": 1, "medium": 2, "large": 4, "enterprise": 8}
STAGE_BY_ENG = [(0.75, "Negotiation"), (0.55, "Proposal"), (0.4, "Discovery"), (0.2, "Qualification"), (0, "Prospecting")]

rows = []
for f in sorted(glob.glob(str(SRC / "rows_*.json"))):
    rows += [r["row"] for r in json.load(open(f))["rows"]]
rng.shuffle(rows)
print("conversations:", len(rows))

deals, acts, contacts, truth, hist, products = [], [], [], [], [], {}
for i, r in enumerate(rows):
    sc = json.loads(r["scenario"]) if isinstance(r["scenario"], str) else r["scenario"]
    persona = sc.get("customer_persona", {})
    name = persona.get("name") or f"Contact {i}"
    company = persona.get("company") or r["company_name"]
    size = (persona.get("company_size") or "medium").lower()
    ptype = r.get("product_type") or "SaaS"
    price = PRICE.get(ptype, 4000) * SIZE_MULT.get(size, 2)
    products[r["product_name"]] = price
    rep = f"Rep {r['company_id'].split('-')[-1]}"
    oid = r["conversation_id"]
    turns = json.loads(r["conversation"]) if isinstance(r["conversation"], str) else r["conversation"]
    eng = float(r.get("customer_engagement") or 0.5)
    outcome = "Won" if int(r["outcome"]) == 1 else "Lost"
    if i >= N_OPEN:  # history: closed deals
        created = AS_OF - timedelta(days=rng.randint(60, 400)); closed = created + timedelta(days=rng.randint(10, 90))
        hist.append(dict(opportunity_id=oid, account=company, product=r["product_name"], sales_agent=rep, outcome=outcome,
                         created_date=created.date(), expected_close=closed.date(), close_value=price if outcome == "Won" else 0))
        continue
    last_customer = max((k for k, t in enumerate(turns) if t["speaker"] == "customer"), default=0)
    gap = rng.randint(1, 8) if eng >= 0.5 else rng.randint(10, 40)
    span = max(len(turns), 3) * (rng.randint(1, 4) if r.get("conversation_flow") == "multi_session" else 1)
    end = AS_OF - timedelta(days=gap); start = end - timedelta(days=span)
    created = start - timedelta(days=rng.randint(1, 10))
    kind = {"sms": "note", "chat": "note", "email": "email", "phone": "call", "call": "call", "video": "meeting"}.get(str(r.get("communication_channel")).lower(), "note")
    for k, t in enumerate(turns):
        d = start + timedelta(days=round(k * span / max(len(turns) - 1, 1)))
        acts.append(dict(activity_id=f"{oid}-{k + 1}", opportunity_id=oid, date=d.date(), type=kind,
                         author=name if t["speaker"] == "customer" else rep, text=t["message"]))
    stage = next(s for th, s in STAGE_BY_ENG if eng >= th)
    deals.append(dict(opportunity_id=oid, account=company, product=r["product_name"], sales_agent=rep, stage=stage,
                      amount=price if rng.random() > 0.15 else "", created_date=created.date(),
                      expected_close=(AS_OF + timedelta(days=rng.randint(7, 60))).date(), primary_contact=name,
                      last_activity_date=end.date(), next_step=rng.choice(["Follow up", "Send proposal", "Schedule demo", ""])))
    contacts.append(dict(opportunity_id=oid, name=name, title=persona.get("role") or "", role="champion"))
    truth.append(dict(opportunity_id=oid, outcome=outcome, actual_close_date=(AS_OF + timedelta(days=30)).date(),
                      actual_close_value=price if outcome == "Won" else 0.0, list_price=price, archetype=r.get("conversation_style"),
                      objection="", correct_next_action="", rep_stage_inflated=False, days_since_buyer_touch=gap, competitor=""))

OUT.mkdir(parents=True, exist_ok=True)
pd.DataFrame(deals).to_csv(OUT / "deals.csv", index=False)
pd.DataFrame(acts).to_csv(OUT / "activities.csv", index=False)
pd.DataFrame(contacts).to_csv(OUT / "contacts.csv", index=False)
pd.DataFrame([{"product": p, "series": "", "sales_price": v} for p, v in products.items()]).to_csv(OUT / "products.csv", index=False)
pd.DataFrame({"sales_agent": sorted({d["sales_agent"] for d in deals}), "manager": "Sales Lead", "regional_office": ""}).to_csv(OUT / "team.csv", index=False)
pd.DataFrame(truth).to_csv(OUT / "ground_truth.csv", index=False)
h = pd.DataFrame(hist); h.to_csv(OUT / "history.csv", index=False)
won = h[h.outcome == "Won"]
(OUT / "profile.json").write_text(json.dumps({"n_closed": len(h), "source": "learned", "base_win_rate": round(float((h.outcome == "Won").mean()), 3),
                                              "median_cycle_days": int((pd.to_datetime(won.expected_close) - pd.to_datetime(won.created_date)).dt.days.median())}, indent=1))
(OUT / "company.md").write_text(f"# SaaS sales conversations — pipeline review brief\n\nAs of {AS_OF.date()}. {len(deals)} open opportunities across "
                                f"{len(products)} SaaS products and {len(set(d['sales_agent'] for d in deals))} reps; records are multi-turn "
                                f"buyer/rep conversations (sms, chat, email, calls). Historical win rate from {len(h)} closed deals: "
                                f"{(h.outcome == 'Won').mean():.0%}.\n")
print(f"open {len(deals)} deals, {len(acts)} activities, history {len(h)} (win rate {(h.outcome == 'Won').mean():.2f}); open-set win rate {sum(t['outcome'] == 'Won' for t in truth) / len(truth):.2f}")
print("stages:", pd.DataFrame(deals).stage.value_counts().to_dict())
